#!/usr/bin/env node
// Writes app/{fr,de,es}/… : one small route file per English page in app/(en), which sets the
// locale and renders the English page module (whose copy goes through t()/tx()).
// Run after adding or removing a page:  node scripts/gen-locale-routes.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const EN = join(ROOT, "app", "(en)");
const LOCALES = ["fr", "de", "es"];
const HEADER = "// Generated by scripts/gen-locale-routes.mjs. Do not edit.\n";

const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const pages = walk(EN).filter((f) => f.endsWith("/page.tsx"));

for (const l of LOCALES) {
  const dir = join(ROOT, "app", l);
  if (existsSync(dir)) rmSync(dir, { recursive: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(
    join(dir, "layout.tsx"),
    `${HEADER}import "../globals.css";
import { SiteShell, shellMetadata } from "@/components/layout/SiteShell";

export { viewport } from "@/components/layout/SiteShell";
export const generateMetadata = () => shellMetadata("${l}");

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return <SiteShell locale="${l}">{children}</SiteShell>;
}
`,
  );
  writeFileSync(
    join(dir, "not-found.tsx"),
    `${HEADER}import NotFound from "@/app/(en)/not-found";
import { setLocale } from "@/lib/i18n/server";

export default function LocalizedNotFound() {
  setLocale("${l}");
  return <NotFound />;
}
`,
  );
  for (const p of pages) {
    const rel = relative(EN, p);
    const src = readFileSync(p, "utf8");
    const imp = `@/app/(en)/${rel.replace(/\.tsx$/, "")}`;
    const lines = [HEADER + `import * as mod from "${imp}";`, `import { localized } from "@/lib/i18n/route";`, ""];
    lines.push(`const page = localized("${l}", mod);`, "export default page.Page;", "export const generateMetadata = page.generateMetadata;");
    if (/export (const|function|async function) generateStaticParams/.test(src)) lines.push(`export { generateStaticParams } from "${imp}";`);
    if (/export const dynamicParams = false/.test(src)) lines.push("export const dynamicParams = false;");
    const out = join(dir, rel);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, lines.join("\n") + "\n");
  }
}
console.log(`locale routes: ${pages.length} pages x ${LOCALES.length} locales`);
